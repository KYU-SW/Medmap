def main() -> int:
    doc = json.loads(CANONICAL.read_text(encoding="utf-8"))
    questions = doc["evidence_questions"]
    clash = sorted(set(QUESTIONS) & set(questions))
    if clash:
        print(f"already applied: {clash[:5]}… — 재실행 금지", file=sys.stderr)
        return 1
    for key, text in QUESTIONS.items():
        questions[key] = {"text_ko": text, "status": "ok", "source": SOURCE_Q}
    doc["evidence_questions"] = {k: questions[k] for k in sorted(questions, key=lambda k: int(k[2:]))}
    for section, table in (("diseases", DISEASES), ("evidence_short", SHORT)):
        for key, label in table.items():
            entry = doc[section][key]
            if entry["status"] != "review_needed":
                print(f"{section}:{key} is not review_needed", file=sys.stderr)
                return 1
            decided = {"label_ko": label, "status": "ok", "source": entry["source"],
                       "note": f"2026-09-27 원문 직역으로 확정(이전 review_needed: {entry['review_reason']})"}
            if "umls_kor_crosscheck" in entry:
                decided["umls_kor_crosscheck"] = entry["umls_kor_crosscheck"]
            doc[section][key] = decided
    doc["version"] = "1.1.0"
    CANONICAL.write_text(json.dumps(doc, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"questions +{len(QUESTIONS)} diseases {len(DISEASES)} short {len(SHORT)} → version 1.1.0")
    return 0


if __name__ == "__main__":
    sys.exit(main())
